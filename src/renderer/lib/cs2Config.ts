import type { CrosshairConfig, ViewmodelConfig, ProConfigProfile } from "@shared/types";

export const DEFAULT_CROSSHAIR: CrosshairConfig = {
  style: 4,
  size: 2.5,
  thickness: 0.5,
  gap: -2,
  colorR: 50,
  colorG: 250,
  colorB: 50,
  outline: true,
  dot: false,
  t: false,
};

export const DEFAULT_VIEWMODEL: ViewmodelConfig = {
  fov: 68,
  offsetX: 2.5,
  offsetY: 0,
  offsetZ: -1.5,
  presetPos: 2,
};

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

/** Keeps generated values inside each convar's documented valid range. */
export function sanitizeCrosshair(c: CrosshairConfig): CrosshairConfig {
  return {
    ...c,
    style: clamp(c.style, 0, 5) as CrosshairConfig["style"],
    size: clamp(c.size, 0, 10),
    thickness: clamp(c.thickness, 0, 3),
    gap: clamp(c.gap, -5, 10),
    colorR: Math.round(clamp(c.colorR, 0, 255)),
    colorG: Math.round(clamp(c.colorG, 0, 255)),
    colorB: Math.round(clamp(c.colorB, 0, 255)),
  };
}

export function sanitizeViewmodel(v: ViewmodelConfig): ViewmodelConfig {
  return {
    ...v,
    fov: clamp(v.fov, 54, 90),
    offsetX: clamp(v.offsetX, -2, 2.5),
    offsetY: clamp(v.offsetY, -2, 2),
    offsetZ: clamp(v.offsetZ, -2, 2),
    presetPos: clamp(v.presetPos, 0, 3) as ViewmodelConfig["presetPos"],
  };
}

/**
 * Generates a real, loadable CS2 config file. Every convar below is a
 * documented, client-side-only Source 2 setting — nothing here touches
 * server-enforced values, nothing bypasses sv_cheats, and nothing is an
 * invented/fabricated command.
 */
export function generateAutoexecCfg(profile: ProConfigProfile): string {
  const x = sanitizeCrosshair(profile.crosshair);
  const v = sanitizeViewmodel(profile.viewmodel);

  const lines = [
    `// Generated by CS Companion — profile "${profile.name}"`,
    `// Place this file in: <CS2 install>/game/csgo/cfg/autoexec.cfg`,
    `// Then set launch option: +exec autoexec.cfg  (or run "exec autoexec" in console)`,
    "",
    "// --- Crosshair ---",
    `cl_crosshairstyle ${x.style}`,
    `cl_crosshairsize ${x.size}`,
    `cl_crosshairthickness ${x.thickness}`,
    `cl_crosshairgap ${x.gap}`,
    `cl_crosshaircolor 5`,
    `cl_crosshaircolor_r ${x.colorR}`,
    `cl_crosshaircolor_g ${x.colorG}`,
    `cl_crosshaircolor_b ${x.colorB}`,
    `cl_crosshair_drawoutline ${x.outline ? 1 : 0}`,
    `cl_crosshairdot ${x.dot ? 1 : 0}`,
    `cl_crosshair_t ${x.t ? 1 : 0}`,
    "",
    "// --- Viewmodel ---",
    `viewmodel_fov ${v.fov}`,
    `viewmodel_offset_x ${v.offsetX}`,
    `viewmodel_offset_y ${v.offsetY}`,
    `viewmodel_offset_z ${v.offsetZ}`,
    `viewmodel_presetpos ${v.presetPos}`,
    "",
    `host_writeconfig`,
    "",
  ];

  return lines.join("\n");
}

export function createEmptyProfile(name: string): ProConfigProfile {
  return {
    id: crypto.randomUUID(),
    name,
    crosshair: { ...DEFAULT_CROSSHAIR },
    viewmodel: { ...DEFAULT_VIEWMODEL },
    updatedAt: new Date().toISOString(),
  };
}
